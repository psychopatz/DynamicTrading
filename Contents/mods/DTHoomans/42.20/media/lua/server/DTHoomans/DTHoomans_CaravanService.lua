-- A caravan physically carries its stock, so its ceiling is the summed carrying
-- capacity of its members. A settlement trader keeps a stocked shop instead.
local function isMobileFaction(faction)
    if type(faction) ~= "table" then return false end
    if PNC.Factions and type(PNC.Factions.IsMobileGroup) == "function" then
        return PNC.Factions.IsMobileGroup(faction) == true
    end
    return type(faction.tags) == "table"
        and faction.tags.mobileGroup == true
end

-- The caravan's carrying limit is the sum of every member's root capacity
-- plus every bag/container capacity. The bag item itself remains part of
-- usedWeight because Project Hoomans owns the canonical inventory state.
function Caravan.GetCapacity(record)
    local faction
    local ids = {}
    local seen = {}
    local usedWeight = 0
    local maxWeight = 0
    local member
    local state
    local item
    local bagCapacity
    local index
    if not record or not PNC or not PNC.Factions
        or type(PNC.Factions.Get) ~= "function"
        or not PNC.Inventory
        or type(PNC.Inventory.GetWeightState) ~= "function"
    then
        return nil
    end
    faction = record.g and PNC.Factions.Get(record.g) or nil
    -- A caravan physically carries its stock, so the summed member capacity is
    -- its ceiling. A settlement trader keeps a stocked shop instead: only mobile
    -- groups use this rule, or a settlement's stock would be capped at the
    -- backpack space of its residents.
    if faction and not isMobileFaction(faction) then return nil end
    if faction and type(faction.memberIDs) == "table" then
        for npcID, _ in pairs(faction.memberIDs) do
            if not seen[npcID] then
                seen[npcID] = true
                ids[#ids + 1] = npcID
            end
        end
    elseif type(record.m) == "table" then
        for index = 1, #record.m do
            if not seen[record.m[index]] then
                seen[record.m[index]] = true
                ids[#ids + 1] = record.m[index]
            end
        end
    end
    for index = 1, #ids do
        member = liveNPC(ids[index])
        if member then
            state = PNC.Inventory.GetWeightState(member)
            if state then
                usedWeight = usedWeight + (tonumber(state.usedWeight) or 0)
                maxWeight = maxWeight + (tonumber(state.maxWeight) or 0)
            end
            for _, item in pairs(member.inventory and member.inventory.items or {}) do
                bagCapacity = tonumber(item.maxWeight) or 0
                if bagCapacity > 0 then maxWeight = maxWeight + bagCapacity end
            end
        end
    end
    if #ids < 1 then return nil end
    return usedWeight, maxWeight
end

-- Project Hoomans owns faction naming. Ask its archetype-aware generator first
-- so a DynamicTrading caravan is named exactly like every other population
-- faction of the same archetype; the literal above is only a degraded fallback.
local function factionName(seed)
    local identity = PNC and PNC.PopulationIdentity or nil
    local generator = PNC and PNC.FactionNameGenerator or nil
    local name
    if identity and type(identity.FactionName) == "function" then
        name = identity.FactionName(FACTION_ARCHETYPE, seed)
    elseif generator and type(generator.GenerateFactionName) == "function" then
        name = generator.GenerateFactionName(FACTION_ARCHETYPE, seed)
    end
    name = type(name) == "string" and name or ""
    if name == "" then return FACTION_NAME_FALLBACK end
    return name
end

-- Canonical faction tags first, DT ownership tags second. Project Hoomans
-- records populationGenerated/mobileGroup/mobilePathMode here, which its
-- mobile-group director reads back from the faction record.
local function factionTags(debug)
    local constants = PNC and PNC.FactionConstants or {}
    local identity = PNC and PNC.PopulationIdentity or nil
    local tags = identity and type(identity.FactionTags) == "function"
        and identity.FactionTags(FACTION_ARCHETYPE, "MOBILE_GROUP") or {}
    -- Guarantee the tags DT itself depends on when the canonical helper is
    -- unavailable, without overriding a value Project Hoomans supplied.
    if tags.mobileGroup == nil then tags.mobileGroup = true end
    if tags.mobilePathMode == nil then
        tags.mobilePathMode = constants.MOBILE_PATH_RANDOM or "random"
    end
    tags.dynamicTrading = true
    -- A trading caravan is the only trade access a region may have, so Project
    -- Hoomans' abstract casualty resolver must not delete it offscreen. The tag
    -- is persisted with the faction record and read by that resolver.
    tags.abstractDeathImmune = true
    -- Only a deliberately spawned test caravan carries the debug marker; the
    -- roaming lifecycle caravans are ordinary world groups.
    if debug == true then tags.debugCaravan = true end
    return tags
end

local function createFaction(seed, at, debug)
    local ok
    local reason
    local faction
    if not PNC or not PNC.Factions
        or type(PNC.Factions.Create) ~= "function"
    then
        return nil, "project_hoomans_faction_unavailable"
    end
    ok, reason, faction = PNC.Factions.Create({
        name = factionName(seed),
        archetypeID = FACTION_ARCHETYPE,
        createdAt = at,
        tags = factionTags(debug),
    })
    if not ok then return nil, reason end
    return faction
end

local function cleanupFaction(factionID, npcIDs, at, reason)
    local index
    local npcID
    if PNC and PNC.Factions
        and type(PNC.Factions.RemoveNPC) == "function"
    then
        for index = #(npcIDs or {}), 1, -1 do
            npcID = npcIDs[index]
            PNC.Factions.RemoveNPC(
                factionID, npcID, reason or "caravan_rollback", at)
        end
    end
    if PNC and PNC.API and type(PNC.API.Despawn) == "function" then
        for index = #(npcIDs or {}), 1, -1 do
            PNC.API.Despawn(npcIDs[index])
        end
    end
    if PNC and PNC.Factions and type(PNC.Factions.Destroy) == "function" then
        PNC.Factions.Destroy(
            factionID, reason or "caravan_rollback", at)
    end
end

local function nativeSpec(state)
    local constants = PNC and PNC.FactionConstants or {}
    local GROUP_SIZE = state.memberCount
    return {
        x = state.x,
        y = state.y,
        z = state.z,
        groupSize = GROUP_SIZE,
        -- One trader plus guards. The faction leader stays at the base, so the
        -- roaming group is generated leaderless with an explicit role order.
        roleOrder = caravanRoleOrder(state.memberCount),
        assignLeader = false,
        -- A caravan that spawns because the player asked for it must be present
        -- at the requested tile, so DT asks for "live" instead of Project
        -- Hoomans' population default (PNC.PopulationIdentity.PresenceSpec()
        -- -> "auto"). The roaming lifecycle uses "auto" and lets Project
        -- Hoomans decide, so an offscreen caravan stays abstract and cheap.
        presenceMode = state.presenceMode or "live",
        allowLive = true,
        useExisting = false,
        mobilePathMode = constants.MOBILE_PATH_RANDOM or "random",
        -- Ambient control is intentionally not used: Hoomans may select a
        -- shelter hundreds of tiles away and replace the requested location
        -- with that ambient objective. Strategic control keeps the native group
        -- director authoritative while its no-target fallback remains inside
        -- the explicit site.
        mobileControlMode = constants.MOBILE_CONTROL_STRATEGIC or "strategic",
        siteSpec = siteFor(
            state.faction.id,
            state.x,
            state.y,
            state.z,
            state.at
        ),
        debug = state.debug == true,
        uniqueNPC = false,
        -- Project Hoomans generation-record shape. `generationId`/`seed`/
        -- `createdAt` are the canonical fields its population pipeline reads;
        -- requestID stays as DT's own transaction key.
        generation = {
            source = "dynamic_trading",
            generationId = state.requestID,
            seed = state.seed,
            createdAt = state.at,
            requestID = state.requestID,
        },
    }
end

local UNRESOLVED_NAMES = {
    [""] = true,
    Unknown = true,
    ["Unknown survivor"] = true,
}

-- Project Hoomans owns NPC identity. Resolve the canonical display name from the
-- live Project Hoomans record instead of keeping a DynamicTrading copy.
function Caravan.ResolveNPCName(npcID)
    local registry = PNC and PNC.Registry or nil
    local identity = PNC and PNC.Identity or nil
    local record
    local summary
    local name
    if npcID == nil or tostring(npcID) == "" then return nil end
    record = registry and type(registry.Get) == "function"
        and registry.Get(tostring(npcID)) or nil
    if type(record) ~= "table" then return nil end
    summary = identity and type(identity.GetCharacterSummary) == "function"
        and identity.GetCharacterSummary(record) or nil
    name = summary and summary.displayName
        or record.identity and record.identity.displayName
        or record.displayName
        or record.name
    name = tostring(name or "")
    if UNRESOLVED_NAMES[name] then return nil end
    return name
end

local function traderNPCID(record)
    local npcID
    local members
    if type(record) ~= "table" then return nil end
    npcID = record.p or record.physicalNpcID
        or record.l or record.leaderNPCID
    if npcID ~= nil and tostring(npcID) ~= "" then return tostring(npcID) end
    members = record.m or record.memberNPCIDs
    if type(members) == "table" and members[1] ~= nil then
        return tostring(members[1])
    end
    return nil
end

-- Canonical name for the trader UI. The DT record carries only the caravan
-- binding; the name always comes from Project Hoomans.
function Caravan.ResolveTraderDisplayName(record)
    return Caravan.ResolveNPCName(traderNPCID(record))
end

local function affiliationRole(npcID)
    local factions = PNC and PNC.Factions or nil
    local affiliation
    if not factions or type(factions.GetNPCAffiliation) ~= "function" then
        return nil
    end
    affiliation = factions.GetNPCAffiliation(npcID)
    return affiliation and tostring(affiliation.role or "") or nil
end

-- DT keeps its gameplay layout (one trader plus armed guards), but the layout
-- is expressed only in Project Hoomans role tokens, and the roaming group is
-- generated with that role order by Project Hoomans itself. The merchant is
-- whichever member Project Hoomans made the caravan trader.
local function merchantFor(npcIDs)
    local leaderID
    local index
    local role
    for index = 1, #npcIDs do
        role = affiliationRole(npcIDs[index])
        if role == MERCHANT_ROLE then return npcIDs[index] end
        if role == LEADER_ROLE and not leaderID then
            leaderID = npcIDs[index]
        end
    end
    return leaderID or npcIDs[1]
end

local function configureMembers(factionID, npcIDs, at)
    local merchantID
    local guardIndex = 0
    local index
    local npcID
    local ok
    local reason

    merchantID = merchantFor(npcIDs)
    if not merchantID then return nil, "merchant_missing" end

    -- No faction leader is assigned here: the caravan's leader resides at the
    -- faction's base (the trader's idle variant), so the roaming members are a
    -- trader plus guards. Project Hoomans is asked to skip the implicit leader
    -- assignment through `assignLeader = false` in the generation spec.
    if PNC.Factions.SetNPCRole then
        ok, reason = PNC.Factions.SetNPCRole(merchantID, MERCHANT_ROLE)
        if not ok and reason ~= "unchanged" then
            return nil, reason or "merchant_role_failed"
        end
    end

    for index = 1, #npcIDs do
        npcID = npcIDs[index]
        if tostring(npcID) ~= tostring(merchantID) then
            guardIndex = guardIndex + 1
            if PNC.Factions.SetNPCRole then
                ok, reason = PNC.Factions.SetNPCRole(npcID, GUARD_ROLE)
                if not ok and reason ~= "unchanged" then
                    return nil, reason or "guard_role_failed"
                end
            end
            -- Guard weapons are a bounded flavour list: guards beyond it stay
            -- unarmed instead of failing a caravan whose size the sandbox
            -- option raised.
            if GUARD_WEAPONS[guardIndex] then
                equipmentDiagnostics(npcID, "before")
                if not PNC.API
                    or type(PNC.API.SetEquipmentSlot) ~= "function"
                then
                    return nil, "project_hoomans_equipment_slot_unavailable"
                end
                ok = PNC.API.SetEquipmentSlot(
                    npcID,
                    "primary",
                    nil,
                    GUARD_WEAPONS[guardIndex]
                )
                equipmentDiagnostics(npcID, "after")
                if not ok then return nil, "guard_equipment_slot_failed" end
            end
        end
    end
    -- The member count owns the caravan's shape, including a trader travelling
    -- alone, so only the trader itself is mandatory here.
    return merchantID
end

local function finish(state, ok, status, caravan)
    if state.finished then return end
    state.finished = true
    PendingSpawns[state.requestID] = nil
    if type(state.onComplete) == "function" then
        local callbackOK, callbackReason = pcall(
            state.onComplete, ok, status, caravan)
        if not callbackOK then
            log("WARN", "spawn_callback_failed request="
                .. tostring(state.requestID) .. " reason="
                .. tostring(callbackReason))
        end
    end
end

local function finalize(state, generated)
    local npcIDs = {}
    local index
    local merchantID
    local merchant
    local traderID
    local record
    local reason
    local bound
    local faction
    local createdCount = tonumber(generated and generated.createdCount) or 0

    for index = 1, #(generated and generated.npcIDs or {}) do
        npcIDs[#npcIDs + 1] = tostring(generated.npcIDs[index])
    end
    local wanted = tonumber(state.memberCount) or MEMBER_COUNT_DEFAULT
    if #npcIDs < wanted or createdCount < wanted then
        cleanupFaction(
            state.faction.id,
            npcIDs,
            state.at,
            "caravan_group_incomplete"
        )
        finish(state, false, "caravan_group_incomplete")
        return false, "caravan_group_incomplete"
    end

    merchantID, reason = configureMembers(
        state.faction.id, npcIDs, state.at)
    if not merchantID then
        cleanupFaction(
            state.faction.id, npcIDs, state.at, reason or "role_setup_failed")
        finish(state, false, reason or "role_setup_failed")
        return false, reason or "role_setup_failed"
    end
    merchant = physicalNPC(merchantID)
    if not merchant then
        cleanupFaction(
            state.faction.id, npcIDs, state.at, "merchant_not_live")
        finish(state, false, "merchant_not_live")
        return false, "merchant_not_live"
    end

    faction = PNC.Factions.Get(state.faction.id) or state.faction

    for index = 1, #npcIDs do
        local member = liveNPC(npcIDs[index])
        if member then
            log("INFO", "caravan_member_position request="
                .. tostring(state.requestID)
                .. " member=" .. tostring(npcIDs[index])
                .. " role=" .. tostring(
                    PNC.Factions.GetNPCAffiliation
                        and PNC.Factions.GetNPCAffiliation(npcIDs[index])
                        and PNC.Factions.GetNPCAffiliation(npcIDs[index]).role)
                .. " pos=" .. tostring(member.x) .. ","
                .. tostring(member.y) .. "," .. tostring(member.z)
                .. " requested=" .. tostring(state.x) .. ","
                .. tostring(state.y) .. "," .. tostring(state.z))
        end
    end

    traderID = "dt_" .. tostring(faction.id)
    if not Service or type(Service.Create) ~= "function"
        or type(Service.BindCaravan) ~= "function"
    then
        cleanupFaction(
            state.faction.id, npcIDs, state.at, "trader_service_unavailable")
        finish(state, false, "trader_service_unavailable")
        return false, "trader_service_unavailable"
    end
    -- No identity in the DT record: Project Hoomans owns the merchant's name and
    -- role. DT keeps trade state plus the caravan binding written below.
    traderID, record = Service.Create({
        traderID = traderID,
        caravanID = "caravan_" .. tostring(faction.id),
        abstractAccessEnabled = true,
    })
    if not traderID or not record then
        cleanupFaction(
            state.faction.id, npcIDs, state.at, "trader_record_failed")
        finish(state, false, "trader_record_failed")
        return false, "trader_record_failed"
    end
    bound, reason = Service.BindCaravan(
        traderID, faction.id, merchantID, npcIDs)
    if not bound then
        if type(Service.Remove) == "function" then
            Service.Remove(traderID)
        end
        cleanupFaction(
            state.faction.id, npcIDs, state.at, reason or "trader_binding_failed")
        finish(state, false, reason or "trader_binding_failed")
        return false, reason or "trader_binding_failed"
    end

    local caravan = {
        traderID = traderID,
        factionID = faction.id,
        leaderNPCID = merchantID,
        leader = merchant,
        memberIDs = npcIDs,
        mobile = generated.mobile,
    }
    log("INFO", "caravan_ready request=" .. tostring(state.requestID)
        .. " trader=" .. tostring(traderID)
        .. " faction=" .. tostring(faction.id)
        .. " members=" .. tostring(#npcIDs)
        .. " path=" .. tostring(generated.pathMode)
        .. " control=" .. tostring(
            generated.mobile and generated.mobile.controlMode))
    finish(state, true, "spawned", caravan)
    return true, "spawned"
end

processState = function(state)
    local ok
    local reason
    local generated
    local callOK
    local finalizeOK
    local finalized
    local finalizeReason
    if type(state) ~= "table" then return false, "spawn_state_missing" end
    if state.finished then return false, "spawn_already_finished" end
    if state.processing then return false, "spawn_already_processing" end
    state.processing = true

    runtimeDiagnostics("processing", state.requestID, state)
    log("INFO", "caravan_processing request=" .. tostring(state.requestID)
        .. " faction=" .. tostring(state.faction and state.faction.id))

    if not PNC or not PNC.MobileGroupDirector
        or type(PNC.MobileGroupDirector.GenerateForFaction) ~= "function"
    then
        cleanupFaction(
            state.faction.id, {}, state.at, "mobile_director_unavailable")
        finish(state, false, "mobile_director_unavailable")
        return false, "mobile_director_unavailable"
    end
    callOK, ok, reason, generated = pcall(
        PNC.MobileGroupDirector.GenerateForFaction,
        state.faction.id,
        nativeSpec(state)
    )
    if not callOK then
        log("WARN", "native_generation_exception request="
            .. tostring(state.requestID) .. " reason=" .. tostring(ok))
        cleanupFaction(
            state.faction.id, {}, state.at, "native_generation_exception")
        finish(state, false, "native_generation_exception")
        return false, "native_generation_exception"
    end
    if not ok then
        log("WARN", "native_generation_failed request="
            .. tostring(state.requestID) .. " reason=" .. tostring(reason))
        cleanupFaction(
            state.faction.id, {}, state.at, reason or "native_generation_failed")
        finish(state, false, reason or "native_generation_failed")
        return false, reason or "native_generation_failed"
    end
    finalizeOK, finalized, finalizeReason = pcall(finalize, state, generated)
    if not finalizeOK then
        log("WARN", "native_finalize_exception request="
            .. tostring(state.requestID) .. " reason="
            .. tostring(finalizeReason))
        if Service and type(Service.Remove) == "function" then
            Service.Remove("dt_" .. tostring(state.faction.id))
        end
        cleanupFaction(
            state.faction.id,
            generated and generated.npcIDs or {},
            state.at,
            "native_finalize_exception"
        )
        finish(state, false, "native_finalize_exception")
        return false, "native_finalize_exception"
    end
    if finalized ~= true then
        runtimeDiagnostics("processed", state.requestID, state)
        return false, finalizeReason or "caravan_finalize_failed"
    end
    runtimeDiagnostics("processed", state.requestID, state)
    return true, finalizeReason or "processed"
end

function Caravan.GetPendingDebug()
    local output = {}
    local requestID
    local state
    for requestID, state in pairs(PendingSpawns) do
        output[#output + 1] = {
            requestID = tostring(requestID),
            factionID = state.faction and tostring(state.faction.id) or nil,
            x = tonumber(state.x) or 0,
            y = tonumber(state.y) or 0,
            z = tonumber(state.z) or 0,
            status = "pending",
        }
    end
    table.sort(output, function(left, right)
        return tostring(left.requestID) < tostring(right.requestID)
    end)
    return output
end

-- Every call creates a new Project Hoomans faction and completes the native
-- generation synchronously. PendingSpawns is an active transaction table for
-- bounded diagnostics only; normal debug spawning never waits for OnTick.
-- Spawn a trading caravan.
--
-- `options` carries the two things that differ between the debug request and the
-- roaming lifecycle: `debug` (test caravan marker) and `presenceMode` ("live"
-- for a requested spawn, "auto" so an offscreen caravan stays abstract). The
-- member count always comes from the mod's sandbox option, so the debug spawn,
-- the roaming lifecycle and the caravan's carry ceiling can never disagree.
function Caravan.Spawn(x, y, z, onComplete, onAccepted, options)
    local at = worldAge()
    local seed
    local faction
    local requestID
    local state
    local request
    local acceptedOK
    local acceptedReason
    local processed
    local processReason

    x = tonumber(x) or 0
    y = tonumber(y) or 0
    z = tonumber(z) or 0
    -- Stable, DT-owned seed for Project Hoomans naming. Deterministic for one
    -- spawn attempt so the generated faction name and emblem stay stable.
    spawnSequence = spawnSequence + 1
    seed = table.concat({
        "dynamic_trading",
        tostring(math.floor(at * 1000)),
        tostring(spawnSequence),
    }, ":")
    options = type(options) == "table" and options or {}
    faction = createFaction(seed, at, options.debug == true)
    if not faction then return nil, "faction_create_failed" end
    requestID = "dt_spawn_" .. tostring(faction.id)
    state = {
        requestID = requestID,
        seed = seed,
        faction = faction,
        x = x,
        y = y,
        z = z,
        at = at,
        memberCount = caravanMemberCount(),
        debug = options.debug == true,
        presenceMode = options.presenceMode,
        onComplete = onComplete,
    }
    PendingSpawns[requestID] = state
    request = {
        requestID = requestID,
        factionID = faction.id,
        status = "processing",
    }
    log("INFO", "caravan_accepted request=" .. tostring(requestID)
        .. " faction=" .. tostring(faction.id)
        .. " pending=" .. tostring(pendingCount())
        .. " runtime=" .. tostring(Runtime))
    runtimeDiagnostics("accepted", requestID, state)
    if type(onAccepted) == "function" then
        acceptedOK, acceptedReason = pcall(onAccepted, request)
        if not acceptedOK then
            log("WARN", "spawn_accept_callback_failed request="
                .. tostring(requestID) .. " reason=" .. tostring(acceptedReason))
        end
    end
    processed, processReason = processState(state)
    request.status = processed and "spawned" or "failed"
    request.reason = processReason
    return request
end

return Caravan
