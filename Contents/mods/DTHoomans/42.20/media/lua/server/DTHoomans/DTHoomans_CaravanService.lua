-- Bounded diagnostics for the live queue audit. The normal spawn path is
-- synchronous, so this table is only an active transaction table; the fields
-- below make duplicate module/table instances and closure mismatches visible
-- in console.txt without producing an unbounded OnTick stream.
local function runtimeDiagnostics(phase, targetRequestID, activeState)
    local count = pendingCount()
    local snapshots = tonumber(Runtime._runtimeDiagnosticSnapshots) or 0
    local entries = 0
    local stateRequestID
    local factionID
    if snapshots >= MAX_RUNTIME_DIAGNOSTIC_SNAPSHOTS then return end
    Runtime._runtimeDiagnosticSnapshots = snapshots + 1
    log("INFO", "caravan_runtime_diag phase=" .. tostring(phase)
        .. " module=" .. tostring(DTHoomans)
        .. " caravan=" .. tostring(Caravan)
        .. " runtime=" .. tostring(Runtime)
        .. " pendingTable=" .. tostring(PendingSpawns)
        .. " runtimePending=" .. tostring(Runtime.PendingSpawns)
        .. " caravanPending=" .. tostring(Caravan.PendingSpawns)
        .. " sameRuntimePending=" .. tostring(
            Runtime.PendingSpawns == PendingSpawns)
        .. " sameCaravanPending=" .. tostring(
            Caravan.PendingSpawns == PendingSpawns)
        .. " pendingCount=" .. tostring(count)
        .. " target=" .. tostring(targetRequestID)
        .. " pendingCountFn=" .. tostring(pendingCount)
        .. " processStateFn=" .. tostring(processState)
        .. " spawnFn=" .. tostring(Caravan.Spawn))
    if activeState then
        log("INFO", "caravan_runtime_active_state phase=" .. tostring(phase)
            .. " state=" .. tostring(activeState)
            .. " requestID=" .. tostring(activeState.requestID)
            .. " factionID=" .. tostring(activeState.faction and activeState.faction.id)
            .. " callback=" .. tostring(activeState.onComplete))
    end
    for requestID, state in pairs(PendingSpawns) do
        entries = entries + 1
        if entries <= MAX_RUNTIME_DIAGNOSTIC_ENTRIES then
            stateRequestID = type(state) == "table" and state.requestID or nil
            factionID = type(state) == "table" and state.faction
                and state.faction.id or nil
            log("INFO", "caravan_runtime_pending phase=" .. tostring(phase)
                .. " key=" .. tostring(requestID)
                .. " value=" .. tostring(state)
                .. " stateRequestID=" .. tostring(stateRequestID)
                .. " factionID=" .. tostring(factionID))
        end
    end
    if entries > MAX_RUNTIME_DIAGNOSTIC_ENTRIES then
        log("INFO", "caravan_runtime_pending_truncated phase="
            .. tostring(phase) .. " entries=" .. tostring(entries)
            .. " limit=" .. tostring(MAX_RUNTIME_DIAGNOSTIC_ENTRIES))
    end
end

local function worldAge()
    local gameTime = getGameTime and getGameTime() or nil
    if gameTime and type(gameTime.getWorldAgeHours) == "function" then
        return math.max(0, tonumber(gameTime:getWorldAgeHours()) or 0)
    end
    return 0
end

local function liveNPC(npcID)
    local registry = PNC and PNC.Registry
    local record = registry and type(registry.Get) == "function"
        and registry.Get(npcID) or nil
    if not record or record.alive == false then return nil end
    return record
end

local function physicalNPC(npcID)
    local record = liveNPC(npcID)
    local liveState = PNC and PNC.Const and PNC.Const.PRESENCE_LIVE
        or "live"
    if not record or record.presenceState ~= liveState then return nil end
    return record
end

local function mapCount(map)
    local count = 0
    for _, _ in pairs(type(map) == "table" and map or {}) do
        count = count + 1
    end
    return count
end

local function mapSummary(map, limit)
    local values = {}
    local count = 0
    limit = tonumber(limit) or 8
    for key, value in pairs(type(map) == "table" and map or {}) do
        count = count + 1
        if #values < limit then
            values[#values + 1] = tostring(key) .. ":" .. tostring(value)
        end
    end
    table.sort(values)
    if count > limit then values[#values + 1] = "..." end
    return table.concat(values, ",")
end

local function liveVisualCount(npcID)
    local registry = PNC and PNC.Registry
    local body
    local visuals
    local ok
    local count
    if not registry or type(registry.GetLiveZombie) ~= "function" then
        return "unavailable"
    end
    body = registry.GetLiveZombie(npcID)
    if not body or type(body.getItemVisuals) ~= "function" then
        return "none"
    end
    ok, visuals = pcall(body.getItemVisuals, body)
    if not ok or not visuals or type(visuals.size) ~= "function" then
        return "unavailable"
    end
    ok, count = pcall(visuals.size, visuals)
    return ok and tostring(count) or "unavailable"
end

